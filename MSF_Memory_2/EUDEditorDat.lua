	    OnPluginStart.lua 의 PatchArr 계열(SetTo)로 쓰는 편이 쉽다 - init() 가 같은 첫 프레임에 이 표 다음에 덮는다.
	  - 적용: EUDEditorPort.lua 의 EUDEditorInit() 가 맵 첫 프레임에 1회 (onPluginStart 자리).

	EUDEditorStatusFnActs = ExtraDataEditor.py 의 "스테이터스인포메이션" 12줄 - 유닛 정보창 함수 표
	(0x5193A0 + 12*유닛 + 4 / +8). 이것은 원래도 절대값(SetTo)이었다.
